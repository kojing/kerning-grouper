"""The browser GUI end to end: upload several fonts, train, look at each tab, download the model."""
import json, os, sys, tempfile, threading, unittest
HERE = os.path.dirname(__file__)
sys.path.insert(0, os.path.join(HERE, '..')); sys.path.insert(0, HERE)
from kg_trainer.server import make_server
from kg_trainer.fontio import FontData
from kg_trainer import pipeline
import make_kerned, test_multifont
from playwright.sync_api import sync_playwright

SHOTS = os.environ.get('KG_SHOTS')  # folder for screenshots, optional


class GUI(unittest.TestCase):
    def test_flow(self):
        tmp = tempfile.mkdtemp()
        fd = FontData(test_multifont.FONT)
        items, _ = pipeline.build_items(fd, test_multifont.CHARS)
        rows, _ = pipeline.pair_table(fd, items, {})
        paths = []
        for i, s in enumerate((-10, 0, 10)):
            paths.append(os.path.join(tmp, f'Pro{i}.otf'))
            open(paths[-1], 'wb').write(test_multifont.pro_font(rows, fd, s, i))
        paths.append(os.path.join(tmp, 'Classes.otf'))
        open(paths[-1], 'wb').write(make_kerned.build(test_multifont.FONT))
        httpd = make_server(0)
        threading.Thread(target=httpd.serve_forever, daemon=True).start()
        url = f'http://127.0.0.1:{httpd.server_address[1]}/'
        try:
            with sync_playwright() as pw:
                b = pw.chromium.launch()
                pg = b.new_page(viewport={'width': 1280, 'height': 900}, accept_downloads=True)
                errors = []
                pg.on('pageerror', lambda e: errors.append(str(e)))
                pg.goto(url)
                self.assertIn('locked', pg.get_attribute('[data-tab=train]', 'class'))
                pg.fill('[data-chars]', test_multifont.CHARS)
                pg.wait_for_timeout(700)
                pg.set_input_files('[data-file]', paths)
                pg.wait_for_selector('.font >> nth=3')
                pg.set_input_files('[data-file]', paths[:1])   # duplicate is rejected
                pg.wait_for_selector('.msg.bad')
                self.assertIn('登録済み', pg.inner_text('[data-msg]'))
                pg.fill('.font >> nth=0 >> [data-license]', 'OFL 1.1')
                pg.press('.font >> nth=0 >> [data-license]', 'Tab')
                pg.wait_for_timeout(300)
                if SHOTS: pg.screenshot(path=os.path.join(SHOTS, '1-fonts.png'), full_page=True)
                pg.click('[data-tab=truth]')
                self.assertEqual(pg.locator('[data-truth] tbody tr').count(), 4)
                if SHOTS: pg.screenshot(path=os.path.join(SHOTS, '2-truth.png'), full_page=True)
                pg.click('[data-tab=train]')
                pg.click('[data-run]')
                pg.wait_for_selector('.stat.hero', timeout=120000)
                self.assertIn('フォント単位の1つ抜き', pg.inner_text('.method'))
                self.assertGreaterEqual(pg.locator('.curve .bar').count(), 3)
                pg.wait_for_selector('.pair .svg svg')
                if SHOTS: pg.screenshot(path=os.path.join(SHOTS, '3-train.png'), full_page=True)
                pg.click('[data-vrun]')
                pg.wait_for_selector('[data-vdl]:not(.hidden)', timeout=120000)
                with pg.expect_download() as vdl:
                    pg.click('[data-vdl]')
                txt = open(vdl.value.path(), encoding='utf-8').read()
                self.assertTrue(txt.startswith('// Generated by kg-trainer'))
                vmod = json.loads(txt[txt.index('export default ') + 15:].rstrip().rstrip(';'))
                self.assertEqual(vmod['format'], 'kerning-grouper-value-model')
                self.assertEqual(len(vmod['meta']['trainingFonts']), 4)
                self.assertIn('evaluation', vmod['meta'])
                pg.click('[data-tab=group]')
                pg.wait_for_selector('[data-group] .stat.hero')
                if SHOTS: pg.screenshot(path=os.path.join(SHOTS, '4-group.png'), full_page=True)
                pg.click('[data-tab=export]')
                self.assertIn('ライセンスが未入力', pg.inner_text('[data-export]'))
                with pg.expect_download() as dl:
                    pg.click('[data-download]')
                pkg = json.load(open(dl.value.path(), encoding='utf-8'))
                self.assertEqual(pkg['format'], 'kerning-grouper-model')
                self.assertEqual(len(pkg['trainingFonts']), 4)
                self.assertEqual(pkg['trainingFonts'][0]['license'], 'OFL 1.1')
                self.assertTrue(pkg['grouping'])
                self.assertTrue(dl.value.suggested_filename.endswith('.kgmodel.json'))
                if SHOTS: pg.screenshot(path=os.path.join(SHOTS, '5-export.png'), full_page=True)
                # switching a font off clears the result and locks the later tabs again
                pg.click('[data-tab=fonts]')
                pg.click('.font >> nth=3 >> .switch')
                pg.wait_for_timeout(400)
                self.assertIn('locked', pg.get_attribute('[data-tab=export]', 'class'))
                pg.set_viewport_size({'width': 390, 'height': 800})
                self.assertLessEqual(pg.evaluate('document.documentElement.scrollWidth'), 390)
                if SHOTS: pg.screenshot(path=os.path.join(SHOTS, '6-mobile.png'), full_page=True)
                self.assertEqual(errors, [])
                b.close()
        finally:
            httpd.shutdown()


if __name__ == '__main__':
    unittest.main()
