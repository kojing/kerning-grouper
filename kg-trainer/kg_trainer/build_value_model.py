"""Train the learned value model from professional fonts and write it for the web tool.

python -m kg_trainer.build_value_model FONT... -o src/kern-model.js [--eval]   (.js: module for the web tool, .json: plain)
Only fonts whose license allows it (OFL, your own) may be used.
"""
import argparse, json, os, sys, time
import numpy as np
from . import core, pipeline, valuemodel as vm
from .fontio import FontData

LATIN = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'


def font_rows(path, chars=LATIN):
    """(features, pro value, pair label) for pairs the tool kerns and the pro kerns."""
    fd = path if isinstance(path, FontData) else FontData(path)
    k = 1000 / fd.upm
    kern = fd.kerning()
    items, _ = pipeline.build_items(fd, chars)
    s = dict(core.KERN_DEFAULTS)
    prepared, ys = core.prepare(items, s['minimum'])
    targets, _, _ = core.targets_from_references(prepared, s['references'], s['spacing'])
    met = font_metrics(fd)
    idx = vm.zone_index(ys, met['cap'])
    X, y, lab = [], [], []
    for ga in items:
        a = prepared[ga['id']]
        for gb in items:
            b = prepared[gb['id']]
            f = core.pair_features(a, b, targets)
            digits = core.case_type(a['unicodes']) == 'D' and core.case_type(b['unicodes']) == 'D'
            if not vm.applies(f['kind'], digits, f) or abs(vm.tool_value(f)) < vm.MIN_TOOL:
                continue
            pro = kern.get((ga['id'], gb['id']), 0) * k
            if abs(pro) < 20:
                continue
            X.append(vm.features(a, b, f, idx, met))
            y.append(pro)
            lab.append(chr(a['unicodes'][0]) + chr(b['unicodes'][0]))
    return X, y, lab, fd


def font_metrics(fd):
    """Cap height / x-height from the font's own H and x (flattened like the web tool), else OS/2."""
    k = 1000 / fd.upm
    seg = {}
    for ch in 'Hx':
        gid = fd.cmap.get(ord(ch))
        if gid is not None:
            seg[ch] = core.flatten(fd.glyph(gid)['commands'], k, .35)
    os2 = fd.font['OS/2'] if 'OS/2' in fd.font else None
    return vm.metrics_from_items(seg.get('H'), seg.get('x'),
                                 getattr(os2, 'sCapHeight', 0) * k if os2 else None, getattr(os2, 'sxHeight', 0) * k if os2 else None)


def build(fonts, evaluate=True, progress=None):
    """fonts: list of (label, FontData or path). Returns the web tool's model dict (meta has the held-out evaluation)."""
    data = []
    for n, (label, src) in enumerate(fonts):
        X, y, lab, fd = font_rows(src)
        data.append((label, fd.family, fd.sha1, np.array(X).reshape(-1, 116), np.array(y), lab))
        if progress:
            progress((n + 1) / (len(fonts) + (len(fonts) if evaluate else 0) + 1))
    if sum(len(d[4]) for d in data) < 30:
        raise ValueError('学習に使えるペアが足りません（プロもツールも値を入れている英字のペアが30組以上必要です）。')
    meta = dict(trainingFonts=[dict(file=d[0], family=d[1], sha1=d[2], pairs=len(d[4])) for d in data], pairs=int(sum(len(d[4]) for d in data)))
    if evaluate and len(data) > 1:
        errs, tool = [], []
        for i in range(len(data)):
            if not len(data[i][4]):
                continue
            Xtr = np.vstack([d[3] for j, d in enumerate(data) if j != i]); ytr = np.concatenate([d[4] for j, d in enumerate(data) if j != i])
            m = vm.export_sklearn(vm.fit(Xtr, ytr))
            pred = np.array([vm.predict(m, x) for x in data[i][3]])
            errs.append(np.abs(pred - data[i][4])); tool.append(np.abs(data[i][3][:, 0] - data[i][4]))
            if progress:
                progress((len(fonts) + i + 1) / (2 * len(fonts) + 1))
        e, t = np.concatenate(errs), np.concatenate(tool)
        meta['evaluation'] = dict(method='leave-one-font-out', tool=dict(mae=float(t.mean()), within=float((t <= 28).mean())),
                                  model=dict(mae=float(e.mean()), within=float((e <= 28).mean()), over=float((e > 56).mean())))
    X = np.vstack([d[3] for d in data]); y = np.concatenate([d[4] for d in data])
    return vm.export_sklearn(vm.fit(X, y), meta)


def as_module(m):
    """src/kern-model.js for the web tool."""
    return ('// Generated by kg-trainer: python -m kg_trainer.build_value_model ... (do not edit by hand)\n'
            '// Trained on OFL fonts; numbers only, no outlines.\nexport default ' + json.dumps(m, ensure_ascii=False, separators=(',', ':')) + ';\n')


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('fonts', nargs='+')
    ap.add_argument('-o', '--out', default='kern-model.json')
    ap.add_argument('--eval', action='store_true', help='leave-one-font-out error before writing')
    a = ap.parse_args(argv)
    t0 = time.time()
    m = build([(os.path.basename(p), p) for p in a.fonts], a.eval)
    ev = m['meta'].get('evaluation')
    if ev:
        print(f"leave-one-font-out: tool {ev['tool']['mae']:.1f} → model {ev['model']['mae']:.1f} (within 28: {ev['model']['within']:.0%})", file=sys.stderr)
    with open(a.out, 'w', encoding='utf-8') as fh:
        fh.write(as_module(m) if a.out.endswith('.js') else json.dumps(m, ensure_ascii=False, separators=(',', ':')))
    print(f'wrote {a.out} ({os.path.getsize(a.out)} bytes, {len(m["trees"])} trees) in {time.time() - t0:.0f}s', file=sys.stderr)


if __name__ == '__main__':
    main()
