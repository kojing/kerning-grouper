"""Train the kerning-priority model (does a designer kern this pair?) from professional fonts.

python -m kg_trainer.build_priority_model FONT... -o src/priority-model.js [--eval]
Pairs: ASCII printable plus common quotes and dashes. Only fonts whose license allows it (OFL, your own).
"""
import argparse, json, os, sys, time
import numpy as np
from . import core, pipeline, valuemodel as vm, priority as pr
from .fontio import FontData
from .build_value_model import font_metrics

CHARS = ''.join(chr(c) for c in range(0x21, 0x7f)) + '‘’“”‚„–—…«»‹›¡¿·'


def font_rows(path, chars=CHARS):
    fd = path if isinstance(path, FontData) else FontData(path)
    k = 1000 / fd.upm
    kern = fd.kerning()
    items, _ = pipeline.build_items(fd, chars)
    s = dict(core.KERN_DEFAULTS)
    prepared, ys = core.prepare(items, s['minimum'])
    targets, _, _ = core.targets_from_references(prepared, s['references'], s['spacing'])
    met = font_metrics(fd)
    idx = vm.zone_index(ys, met['cap'])
    X, y = [], []
    for ga in items:
        a = prepared[ga['id']]
        for gb in items:
            b = prepared[gb['id']]
            f = core.pair_features(a, b, targets)
            X.append(pr.features(a, b, f, idx, met))
            y.append(abs(kern.get((ga['id'], gb['id']), 0) * k) >= pr.LABEL_MIN)
    return np.array(X), np.array(y), fd


def build(fonts, evaluate=True):
    data = [(label,) + font_rows(src) for label, src in fonts]
    meta = dict(trainingFonts=[dict(file=d[0], family=d[3].family, sha1=d[3].sha1, pairs=int(len(d[2])), kerned=int(d[2].sum())) for d in data], labelMin=pr.LABEL_MIN, chars=CHARS)
    if evaluate and len(data) > 1:
        from sklearn.metrics import roc_auc_score
        P, Y, T = [], [], []
        for i in range(len(data)):
            Xtr = np.vstack([d[1] for j, d in enumerate(data) if j != i]); ytr = np.concatenate([d[2] for j, d in enumerate(data) if j != i])
            P.append(pr.fit(Xtr, ytr).predict_proba(data[i][1])[:, 1]); Y.append(data[i][2]); T.append(np.abs(data[i][1][:, 0]) >= 20)
        p, y, t = np.concatenate(P), np.concatenate(Y), np.concatenate(T)
        def prf(pred):
            tp = int((pred & y).sum()); pp = tp / max(1, pred.sum()); rr = tp / max(1, y.sum()); return dict(precision=pp, recall=rr, f1=2 * pp * rr / max(1e-9, pp + rr), kerned=float(pred.mean()))
        meta['evaluation'] = dict(method='leave-one-font-out', auc=float(roc_auc_score(y, p)), pro=float(y.mean()), tool=prf(t), **{f'p{int(th*100)}': prf(p >= th) for th in (.2, .3, .4, .5)})
    X = np.vstack([d[1] for d in data]); y = np.concatenate([d[2] for d in data])
    return pr.export_sklearn(pr.fit(X, y), meta)


def as_module(m):
    return ('// Generated by kg-trainer: python -m kg_trainer.build_priority_model ... (do not edit by hand)\n'
            '// Trained on OFL fonts; numbers only, no outlines.\nexport default ' + json.dumps(m, ensure_ascii=False, separators=(',', ':')) + ';\n')


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('fonts', nargs='+')
    ap.add_argument('-o', '--out', default='priority-model.json')
    ap.add_argument('--eval', action='store_true')
    a = ap.parse_args(argv)
    t0 = time.time()
    m = build([(os.path.basename(p), p) for p in a.fonts], a.eval)
    ev = m['meta'].get('evaluation')
    if ev:
        print(f"leave-one-font-out AUC {ev['auc']:.3f}; F1 tool {ev['tool']['f1']:.3f} → p≥0.3 {ev['p30']['f1']:.3f}", file=sys.stderr)
    with open(a.out, 'w', encoding='utf-8') as fh:
        fh.write(as_module(m) if a.out.endswith('.js') else json.dumps(m, ensure_ascii=False, separators=(',', ':')))
    print(f'wrote {a.out} ({os.path.getsize(a.out)} bytes, {len(m["trees"])} trees) in {time.time() - t0:.0f}s', file=sys.stderr)


if __name__ == '__main__':
    main()
